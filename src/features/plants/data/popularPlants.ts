/**
 * Popular indoor houseplants: the catalog the Library grid ranks by climate (docs/search-spec.md §3).
 *
 * Nine of them are seed species and reuse those entries by id. The rest are complete
 * `PlantSpecies` records, so opening one is instant and offline, exactly like a seed — no Perenual
 * request, which matters on a 100-request daily quota.
 *
 * Popularity is a hand ranking informed by the usual "most popular houseplants" lists (RHS, The
 * Sill, Bloomscape, Gardening Know How) — no live source publishes one. Care traits follow RHS /
 * university extension guidance, and ASPCA for pet toxicity. Photos are Unsplash, hotlinked as Unsplash's guidelines require, with the
 * photographer recorded beside each one.
 */

export type LightTolerance = 'low' | 'medium' | 'bright';
export type HumidityNeed = 'low' | 'medium' | 'high';

export type PopularPlant = {
  /** The lowest humidity it is happy with indoors. */
  humidityNeed: HumidityNeed;
  /** The dimmest light it tolerates — what decides how it copes with a short winter day. */
  minLight: LightTolerance;
  /** The coldest it tolerates without damage, e.g. by a winter window. */
  minTempC: number;
  /** Wants several hours of direct sun (cacti, succulents, bird of paradise). */
  needsFullSun: boolean;
  /** 1 is the most popular. */
  popularityRank: number;
  speciesId: string;
};

function unsplash(url: string): { uri: string } {
  return { uri: url };
}

